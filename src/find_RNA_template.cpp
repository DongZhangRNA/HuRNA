FindRNATemplate::FindRNATemplate(Cobmms *cbs) : Pointers(cbs) {}

FindRNATemplate::FindRNATemplate(const FindRNATemplate &other) : Pointers(other.cbs) {
  Vtemplate_scores=other.Vtemplate_scores;
  Vtemplates=other.Vtemplates;
}

FindRNATemplate& FindRNATemplate::operator=(const FindRNATemplate &other) {
  if(this != &other) {
    Pointers::operator=(other.cbs);
    Vtemplate_scores=other.Vtemplate_scores;
    Vtemplates=other.Vtemplates;
  }

  return *this;
}

FindRNATemplate::~FindRNATemplate() {
  Vtemplate_scores.clear();
  Vtemplate_scores.shrink_to_fit();
  Vtemplates.clear();
  Vtemplates.shrink_to_fit();  
}

void FindRNATemplate::find_template(const RNAMotif &motif_one) {
  if(motif_one.type=="Hairpin") {
    if(init->RNA_use_DM) 
      FindRNATemplate::find_template_DM(motif_one);
    else
      FindRNATemplate::find_Hairpin(motif_one);
  }
  else if(motif_one.type=="Tail5" || motif_one.type=="Tail3") 
    FindRNATemplate::find_Tail(motif_one);
  else if(motif_one.type=="Hairpin_kiss") {
    if(init->RNA_use_DM)
      FindRNATemplate::find_template_DM(motif_one);
    else
      FindRNATemplate::find_Hairpin_kiss(motif_one);
  }
  else if(motif_one.type.find("way_junction")!=string::npos && motif_one.type.find("kiss")==string::npos) {
    if(init->RNA_use_DM)
      FindRNATemplate::find_template_DM(motif_one);
    else
      FindRNATemplate::find_Junction(motif_one);
  }
  else if(motif_one.type.find("way_junction_kiss")!=string::npos) 
    FindRNATemplate::find_Junction_kiss(motif_one);
  else if(motif_one.type=="Loop")
    FindRNATemplate::find_Loop(motif_one);
  else if(motif_one.type=="Loop_kiss_loop")
    FindRNATemplate::find_Loop_kiss_loop(motif_one);
  else {
    string str="find_RNA_template.cpp: Unknown motif type --> "+motif_one.type;
    error->warning(str);  
  }
}

void FindRNATemplate::find_template_DM(const RNAMotif &motif_one) {
  Vtemplate_scores.clear();
  Vtemplates.clear();

  string fstr=init->WORK_DIR+"DM-input.dat";
  string fout=init->WORK_DIR+"DM-output.pdb";
  ofstream outF (fstr.c_str());
  outF<<motif_one.get_RNA_motif_info()<<endl;
  outF.close(); outF.clear();

  string cmd=init->RNA_DM+" "+fstr+" "+fout;  //command to execute RNA DM
  cbs->execute_system_command(cmd);

  ReadPDB readpdb_one(cbs);
  readpdb_one.read_PDB(fout);
  if(readpdb_one.RNA_atoms.size()==0 || readpdb_one.RNA_atoms[0].size()==0) {
    string str="find_RNA_template.cpp: No RNA atom in "+fout;
    error->one(str);
  }
  Molecule mol_one(cbs);
  mol_one.set_molecule(readpdb_one.RNA_atoms[0],Chain::rna);

  MatchRNAMotif MRmotif_one(cbs);
  MRmotif_one.match_score=0;
  MRmotif_one.sequence_similarity=1.0; //replace with RNA_DM score?
  string match_code="";
  for(size_t jj=0;jj<motif_one.lengths.size();jj++)
    match_code+="1";
  MRmotif_one.match_code=match_code;  
  MRmotif_one.template_info="Generated by RNA_DM";

  RNAMotif template_one(cbs);
  template_one.type=motif_one.type;
  template_one.secstrs=motif_one.secstrs;
  size_t nchain=motif_one.ends.size()/2;
  for(size_t ii=0;ii<nchain;ii++) {
    string residue_begin=motif_one.ends[ii*2];
    string residue_end=motif_one.ends[ii*2+1];
    vector<string> stoken=split_string(residue_begin,"/");
    string chainid_one=stoken[0];
    Chain loop_i(cbs);
    int check=0;
    for(size_t jj=0;jj<mol_one.size();jj++) {
      for(int kk=0;kk<(int)mol_one.chains[jj].size();kk++) {
        if(mol_one.chains[jj].chainid!=chainid_one) continue;
        if(mol_one.chains[jj][kk].get_residue_name()==residue_begin) {
          if(kk+motif_one.lengths[ii]+1>=(int)mol_one.chains[jj].size()) break;
          else if(mol_one.chains[jj][kk+motif_one.lengths[ii]+1].get_residue_name()!=residue_end) continue;
          else {
            loop_i.insert_residue(mol_one.chains[jj][kk],Chain::end);
            check=1;
            continue;
          } 
        }
        if(check==1 && mol_one.chains[jj][kk].get_residue_name()==residue_end) {
          loop_i.insert_residue(mol_one.chains[jj][kk],Chain::end);
          check=2;
          break;
        }
        if(check==1) loop_i.insert_residue(mol_one.chains[jj][kk],Chain::end);
      }
      if(check==2) break;
    }
    loop_i.chain_label=Chain::rna;
    template_one.insert_RNA_segment(loop_i,-2);
    if(check==0) {
      string str="find_RNA_template.cpp: Cannot find residues "+residue_begin+"-"+residue_end+" in file "+fout;
      error->one(str);
    }
  }

  Vtemplate_scores.push_back(MRmotif_one);
  Vtemplates.push_back(template_one);
}

void FindRNATemplate::find_Hairpin(const RNAMotif &motif_one) {
  Vtemplate_scores.clear();
  Vtemplates.clear();

  if(motif_one.type!="Hairpin") {
    string str="find_RNA_template.cpp: Incorrected motif type --> "+motif_one.type;
    error->warning(str);
    return;
  }

  string template_name=motif_one.get_RNA_motif_name();
  ReadRNATemplate RRtemplate_one(cbs,template_name);
  if(RRtemplate_one.is_template_exist()) {
    RRtemplate_one.read_templates();
    vector<MatchRNAMotif> template_candidates;
    for(size_t ii=0;ii<RRtemplate_one.template_list.size();ii++) {
      double sequence_similarity_max=0.0;
      MatchRNAMotif MRmotif_best(cbs);
      int check=0;
      for(size_t jj=0;jj<RRtemplate_one.template_list[ii].size();jj++) {
        string template_one=RRtemplate_one.template_list[ii][jj];
        vector<string> stoken=split_string(template_one);
        string PDBid=stoken[0];
        if(init->Excluded_PDBs.size()>0 && count(init->Excluded_PDBs.begin(),init->Excluded_PDBs.end(),PDBid)>0) continue;
        MatchRNAMotif MRmotif_one(cbs);
        MRmotif_one.get_match_score(motif_one,template_one);
        if(MRmotif_one.sequence_similarity>sequence_similarity_max) {
          check=1;
          sequence_similarity_max=MRmotif_one.sequence_similarity;
          MRmotif_best=MRmotif_one;
        }
      }
      if(check) template_candidates.push_back(MRmotif_best);
    } 

    if(template_candidates.size()>0) {
      FindRNATemplate::select_template(template_candidates,RRtemplate_one);
    }
  }

  if(Vtemplates.size()==0) { //find the alternative Hairpin with smaller size
    string fversion=init->RNA_TEMPLATE_DIR+"version.txt";
    if(!is_file_exist(fversion)) {
      string str="find_RNA_template.cpp: Cannot open "+fversion;
      error->one(str);
    }
    vector<string> name_list;
    vector<string> Vlines=read_file(fversion);
    int check=0;
    for(size_t ii=0;ii<Vlines.size();ii++) {
      if(Vlines[ii].find("#List of templates")!=string::npos)
        {check=1; continue;}
      if(check==0) continue;
      vector<string> stoken=split_string(Vlines[ii],":");
      string name=stoken[0];
      stoken=split_string(name,"#");
      string type=stoken[0];
      if(type==motif_one.type)
        name_list.push_back(name);
    }

    if(init->Excluded_PDBs.size()>0) {
      vector<string> Vname_list=name_list;
      name_list.clear();
      for(size_t ii=0;ii<Vname_list.size();ii++) {
        ReadRNATemplate RRtemplate_tmp(cbs,Vname_list[ii]);
        if(!RRtemplate_tmp.is_template_exist()) continue;
        RRtemplate_tmp.read_templates();
        int check=0;
        for(size_t jj=0;jj<RRtemplate_tmp.template_list.size();jj++) {
          for(size_t kk=0;kk<RRtemplate_tmp.template_list[jj].size();kk++) {
            vector<string> stoken=split_string(RRtemplate_tmp.template_list[jj][kk]);
            string PDBid=stoken[0];
            if(count(init->Excluded_PDBs.begin(),init->Excluded_PDBs.end(),PDBid)==0) {
              check=1;
              break;
            }
          }
          if(check) break;
        }
        if(check) name_list.push_back(Vname_list[ii]);
      }
    }

    if(name_list.size()==0) return;

    int diff_length_min=1000;
    string name_alt="";
    for(size_t ii=0;ii<name_list.size();ii++) {
      vector<string> stoken=split_string(name_list[ii],"#&");
      int diff_length=motif_one.lengths[0]-stoi(stoken[1]);
      if(diff_length<0) continue;
      if(diff_length%2!=0) continue;
      if(diff_length<diff_length_min) {
        diff_length_min=diff_length;
        name_alt=name_list[ii];
      }
    }

    ReadRNATemplate RRtemplate_alt(cbs,name_alt);
    if(!RRtemplate_alt.is_template_exist()) return;
    RRtemplate_alt.read_templates();
    for(size_t ii=0;ii<RRtemplate_alt.template_list.size();ii++) {
      int check=0;
      for(size_t jj=0;jj<RRtemplate_alt.template_list[ii].size();jj++) {
        string template_one=RRtemplate_alt.template_list[ii][jj];
        vector<string> stoken=split_string(template_one);
        string PDBid=stoken[0];
        if(init->Excluded_PDBs.size()>0 && count(init->Excluded_PDBs.begin(),init->Excluded_PDBs.end(),PDBid)>0) continue;
        check=1;
        MatchRNAMotif MRmotif_alt(cbs);
        MRmotif_alt.get_match_score(motif_one,template_one);
        Vtemplate_scores.push_back(MRmotif_alt);
        RNAMotif template_xyz=RRtemplate_alt.read_template_full(template_one);
        Vtemplates.push_back(template_xyz);
        break;
      }
      if(check) break;
    }
  }
}

