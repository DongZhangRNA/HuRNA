void FindRNATemplate::select_template(vector<MatchRNAMotif> &template_candidates, ReadRNATemplate &RRtemplate_one) {
  double sequence_similarity_max=0.0;
  for(size_t ii=0;ii<template_candidates.size();ii++) {
    if(template_candidates[ii].sequence_similarity>sequence_similarity_max)
      sequence_similarity_max=template_candidates[ii].sequence_similarity;
  }

  if(sequence_similarity_max >= init->RNA_sequence_similarity_high) {
    for(size_t ii=0;ii<template_candidates.size();ii++) {
      if(template_candidates[ii].sequence_similarity >= init->RNA_sequence_similarity_high) {
        Vtemplate_scores.push_back(template_candidates[ii]);
        RNAMotif template_xyz=RRtemplate_one.read_template_full(template_candidates[ii].template_info);
        Vtemplates.push_back(template_xyz);
        if((int)Vtemplates.size()==init->RNA_template_nmax) break;
      } 
    }
  }
  else if(sequence_similarity_max >= init->RNA_sequence_similarity_medium && sequence_similarity_max < init->RNA_sequence_similarity_high) {
    vector<MatchRNAMotif> Vtmp=template_candidates;
    template_candidates.clear();
    vector<double> Vscore;
    for(size_t ii=0;ii<Vtmp.size();ii++) {
      if(Vtmp[ii].sequence_similarity >= init->RNA_sequence_similarity_medium) {
        template_candidates.push_back(Vtmp[ii]);
        Vscore.push_back(Vtmp[ii].sequence_similarity);
      }
    }
    vector<size_t> Vsort=SortVector::sort_vector_descending(Vscore);
    int nmax=static_cast<int>(Vscore.size());
    if(nmax > init->RNA_template_nmax)
      nmax=init->RNA_template_nmax;
    for(int ii=0;ii<nmax;ii++) {
      size_t index_i=Vsort[ii];
      Vtemplate_scores.push_back(template_candidates[index_i]);
      RNAMotif template_xyz=RRtemplate_one.read_template_full(template_candidates[index_i].template_info);
      Vtemplates.push_back(template_xyz);
    }
  }
  else {
    int nmax=static_cast<int>(template_candidates.size());
    if(nmax > init->RNA_template_nmax)
      nmax=init->RNA_template_nmax;
    for(int ii=0;ii<nmax;ii++) {
      Vtemplate_scores.push_back(template_candidates[ii]);
      RNAMotif template_xyz=RRtemplate_one.read_template_full(template_candidates[ii].template_info);
      Vtemplates.push_back(template_xyz);
    }
  }
}